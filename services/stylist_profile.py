"""
Карточка мастера: описание о себе.

До этого в карточке были только имя, рейтинг и адрес салона — все мастера
выглядели одинаково, и выбирать клиенту было не по чему.
"""

#: Ограничение колонки stylists.about. Обрезаем на входе, чтобы не ловить
#: ошибку базы после того, как человек уже написал текст.
ABOUT_MAX_LEN = 500


def normalize_about(raw: str | None) -> str | None:
    """
    Описание мастера: без хвостовых пробелов, не длиннее колонки.

    Переносы строк сохраняются — мастер мог разбить текст на строки,
    и склеивать их в одну значит портить написанное. Пустая строка
    превращается в None: «не заполнено» и «заполнено пустотой» должны
    выглядеть одинаково и в карточке, и в проверках.
    """
    if not raw:
        return None
    cleaned = "\n".join(line.strip() for line in raw.strip().splitlines())
    cleaned = cleaned[:ABOUT_MAX_LEN].strip()
    return cleaned or None
